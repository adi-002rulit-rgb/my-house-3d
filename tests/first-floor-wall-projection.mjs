import assert from 'node:assert/strict';
import {APPROVED_HOUSE_V1} from '../shared/approved-house-v1.mjs';
import {architectureGeometry} from '../shared/architecture-geometry.mjs';
import {consolidatedPinnedWallProjection} from '../shared/first-floor-wall-projection.mjs';
const before=JSON.stringify(APPROVED_HOUSE_V1);
const legacy=architectureGeometry(APPROVED_HOUSE_V1);
const result=architectureGeometry(APPROVED_HOUSE_V1,{consolidateOverlappingWalls:true});
assert.equal(result.wallProjection.applied,true);
assert.equal(result.wallProjection.duplicateAreaM2,2.053);
assert.equal(result.segments.length,legacy.segments.length);
assert.equal(legacy.segments.filter(s=>s.sourceWall==='livingBack').length,1);
assert.equal(legacy.segments.filter(s=>s.sourceWall==='bedFront').length,1);
assert.equal(result.segments.filter(s=>s.sourceWall==='livingBack').length,0);
assert.equal(result.segments.filter(s=>s.sourceWall==='bedFront').length,0);
const merged=result.segments.filter(s=>s.presentationOnly);
assert.equal(merged.length,2);
assert.ok(merged.every(s=>s.h===APPROVED_HOUSE_V1.model.height));
assert.ok(merged.every(s=>s.sourceWallIds.join('|')==='livingBack|bedFront'));
assert.equal(result.openings.length,legacy.openings.length);
assert.deepEqual(result.openings,legacy.openings);
assert.deepEqual(result.slabs,legacy.slabs);
assert.deepEqual(result.treads,legacy.treads);
assert.deepEqual(result.furniture,legacy.furniture);
assert.deepEqual(result.floors,legacy.floors);
assert.deepEqual(result.counts,legacy.counts);
assert.equal(JSON.stringify(APPROVED_HOUSE_V1),before,'original approved model preserved');
const withDoor=structuredClone(APPROVED_HOUSE_V1);
withDoor.model.openings.push({...withDoor.model.openings[0],id:'testDecorOpening',
 wall:'livingBack',offset:4.0,width:1.0,sill:0,head:2});
const projected=architectureGeometry(withDoor,{consolidateOverlappingWalls:true});
assert.equal(projected.wallProjection.applied,false,'fail closed if source wall contains an opening');
assert.equal(projected.wallProjection.reason,'apertures-require-review');
assert.equal(projected.segments.some(s=>s.presentationOnly),false);
const direct=consolidatedPinnedWallProjection(APPROVED_HOUSE_V1.model,legacy.segments);
assert.equal(direct.applied,true);
console.log('PASS: opt-in wall projection preserves architectural source, openings, stairs and furniture');
